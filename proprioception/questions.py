def whole_bit_wording(text: str) -> str:
    for pattern, replacement in _WHOLE_BIT_REWRITES:
        text = re.sub(pattern, replacement, text)
    return re.sub(r"\d+\.\d", lambda m: str(round(float(m.group(0)))), text)


