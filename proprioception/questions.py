def format_token_ref(token_text: str, occurrence: int, total: int) -> str:
    quoted = f"the token '{token_text}'"
    if total <= 1:
        return quoted
    rank = {1: "1st", 2: "2nd", 3: "3rd"}.get(occurrence, f"{occurrence}th")
    return f"the {rank} occurrence of {quoted}"


@dataclasses.dataclass
class BinaryExpertQuestion:
    text: str
    correct_letter: str
    true_expert: int
    distractor_expert: int
    layer: int
    key_word: str


def sample_distractor(rng: random.Random, num_experts: int, topk_experts: list[int]) -> int:
    candidates = [e for e in range(num_experts) if e not in set(topk_experts)]
    if not candidates:
        raise ValueError(f"No distractor available: top-k covers all {num_experts} experts")
    return rng.choice(candidates)


def render_token_context(rng: random.Random, sentence: str) -> tuple[str, str]:
    context_template, question_template = rng.choice(TOKEN_TEMPLATES)
    return context_template.format(sentence=sentence), question_template


def compose_token_question(
    rng: random.Random,
    question_template: str,
    *,
    token_ref: str,
    layer: int,
    true_expert: int,
    distractor_expert: int,
) -> BinaryExpertQuestion:
    true_is_a = rng.random() < 0.5
    option_a, option_b = (true_expert, distractor_expert) if true_is_a else (distractor_expert, true_expert)
    text = question_template.format(token_ref=token_ref, layer=layer, option_a=option_a, option_b=option_b)
    return BinaryExpertQuestion(
        text=text,
        correct_letter="A" if true_is_a else "B",
        true_expert=true_expert,
        distractor_expert=distractor_expert,
        layer=layer,
        key_word=token_ref,
    )


