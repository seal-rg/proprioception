EXPERT_MENTION = re.compile(r"expert(?:\s+(?:number|id|index|no\.?))?\s*#?\s*(\d+)", re.IGNORECASE)


def parse_expert_id(reply: str, num_experts: int) -> int | None:
    named = [int(m) for m in EXPERT_MENTION.findall(reply) if int(m) < num_experts]
    if named:
        return named[-1]
    candidates = [int(m) for m in re.findall(r"\d+", reply) if int(m) < num_experts]
    return candidates[-1] if candidates else None


LAYER_MENTION = re.compile(r"layer\s*#?\s*(\d+)", re.IGNORECASE)


def parse_bounded_expert_id(
    reply: str, num_experts: int, *, max_chars: int = 60, markers: ReasoningMarkers = DEFAULT_REASONING
) -> int | None:
    text = reply.strip()
    if markers.open in text or markers.close in text or "\n" in text or len(text) > max_chars:
        return None
    named = {int(m) for m in EXPERT_MENTION.findall(text)}
    if named:
        if len(named) != 1:
            return None
        answer = named.pop()
        return answer if answer < num_experts else None
    layers = {m.start(1) for m in LAYER_MENTION.finditer(text)}
    numbers = [int(m.group()) for m in re.finditer(r"\d+", text) if m.start() not in layers]
    if len(numbers) != 1 or numbers[0] >= num_experts:
        return None
    return numbers[0]


def _bounded_text(reply: str, max_chars: int, markers: ReasoningMarkers) -> str | None:
    text = reply.strip()
    if markers.open in text or markers.close in text or "\n" in text or len(text) > max_chars:
        return None
    return text


def parse_bounded_integer(
    reply: str,
    bound: int,
    *,
    max_chars: int = 60,
    layer_is_answer: bool = False,
    markers: ReasoningMarkers = DEFAULT_REASONING,
) -> int | None:
    text = _bounded_text(reply, max_chars, markers)
    if text is None:
        return None
    layers = set() if layer_is_answer else {m.start(1) for m in LAYER_MENTION.finditer(text)}
    numbers = [m for m in re.finditer(r"\d+(?:\.\d+)?", text) if m.start() not in layers]
    if len(numbers) != 1 or "." in numbers[0].group():
        return None
    value = int(numbers[0].group())
    return value if value < bound else None


def parse_bounded_decimal(
    reply: str, whole_bound: int, *, max_chars: int = 60, markers: ReasoningMarkers = DEFAULT_REASONING
) -> int | None:
    text = _bounded_text(reply, max_chars, markers)
    if text is None:
        return None
    layers = {m.start(1) for m in LAYER_MENTION.finditer(text)}
    numbers = [m for m in re.finditer(r"\d+(?:\.\d+)?", text) if m.start() not in layers]
    if len(numbers) != 1:
        return None
    whole, _, tenth = numbers[0].group().partition(".")
    if len(tenth) > 1 or int(whole) >= whole_bound:
        return None
    return int(whole) * 10 + (int(tenth) if tenth else 0)


def token_answer_forms(token_text: str) -> set[str]:
    forms = {token_text.strip(), token_text.encode("unicode_escape").decode("ascii").strip()}
    return {form for form in forms if form}


def parse_bounded_token(
    reply: str,
    *,
    max_chars: int = 60,
    prefixes: Sequence[str] = (),
    markers: ReasoningMarkers = DEFAULT_REASONING,
) -> set[str] | None:
    text = _bounded_text(reply, max_chars, markers)
    if text is None:
        return None
    readings = {text}
    for prefix in prefixes:
        if text.startswith(prefix) and text[len(prefix) :].strip():
            readings.add(text[len(prefix) :].strip())
    for reading in list(readings):
        for quote in ('"', "'", "`"):
            if len(reading) >= 2 and reading.startswith(quote) and reading.endswith(quote):
                readings.add(reading[1:-1])
    for reading in list(readings):
        if len(reading) > 1 and reading.endswith(".") and not reading.endswith(".."):
            readings.add(reading[:-1].rstrip())
    for reading in list(readings):
        for quote in ('"', "'", "`"):
            if len(reading) >= 2 and reading.startswith(quote) and reading.endswith(quote):
                readings.add(reading[1:-1])
    return {reading for reading in readings if reading}


ANSWER_QUOTES = (
    ('"', '"'),
    ("\u201c", "\u201d"),
    ("\u201e", "\u201c"),
    ("\u201e", "\u201d"),
    ("\u00ab", "\u00bb"),
    ("\u00bb", "\u00ab"),
    ("\u2018", "\u2019"),
    ("'", "'"),
    ("`", "`"),
)


def quoted_span(text: str) -> tuple[int, int] | None:
    for opening, closing in ANSWER_QUOTES:
        openings = [i for i, ch in enumerate(text) if ch == opening]
        closings = [i for i, ch in enumerate(text) if ch == closing]
        if opening == "'":
            openings = [i for i in openings if i == 0 or not text[i - 1].isalnum()]
            closings = [i for i in closings if i == len(text) - 1 or not text[i + 1].isalnum()]
        if openings and closings and openings[0] < closings[-1]:
            return openings[0] + 1, closings[-1]
    return None


def final_quoted_span(text: str, max_chars: int) -> tuple[int, int] | None:
    close = len(text.rstrip(string.whitespace + "*.!")) - 1
    if close < 1:
        return None
    for opening, closing in ANSWER_QUOTES:
        if text[close] != closing:
            continue
        start = text.rfind(opening, 0, close)
        if start < 0 or (opening == "'" and start > 0 and text[start - 1].isalnum()):
            continue
        quoted = text[start + 1 : close]
        if quoted and len(quoted) <= max_chars and "\n" not in quoted and closing not in quoted:
            return start + 1, close
    return None


def quoted_answer(text: str) -> str | None:
    span = quoted_span(text)
    return None if span is None else text[span[0] : span[1]]


def token_reply_matches(
    reply: str,
    label_text: str,
    *,
    names_none: bool = False,
    max_chars: int = 60,
    prefixes: Sequence[str] = (),
    markers: ReasoningMarkers = DEFAULT_REASONING,
) -> bool:
    text = _bounded_text(reply, max_chars, markers)
    if text is None:
        return False
    quoted = quoted_answer(text)
    if quoted is not None:
        if names_none:
            return quoted.strip().lower() == "none"
        return quoted in (label_text, label_text.encode("unicode_escape").decode("ascii"))
    readings = parse_bounded_token(text, max_chars=max_chars, prefixes=prefixes, markers=markers) or set()
    if names_none:
        return any(reading.lower() == "none" for reading in readings)
    return bool(readings & token_answer_forms(label_text))


def parse_bare_expert_id(reply: str, num_experts: int, markers: ReasoningMarkers = DEFAULT_REASONING) -> int | None:
    if markers.open in reply or markers.close in reply:
        return None
    numbers = re.findall(r"\d+", reply)
    if len(numbers) != 1 or int(numbers[0]) >= num_experts:
        return None
    return int(numbers[0])


def parse_letter_answer(reply: str) -> str | None:
    tokens = reply.upper().replace("*", " ").replace("'", " ").replace('"', " ").split()
    choices = []
    for token in tokens:
        stripped = token.strip(".,:;()[]!?")
        if stripped in ("A", "B"):
            choices.append(stripped)
    unique = set(choices)
    if len(unique) == 1:
        return unique.pop()
    return None
